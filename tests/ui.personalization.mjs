import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium, webkit } from 'playwright';
import { fixture } from './ui.fixture.mjs';
const engine = process.env.UI_BROWSER === 'webkit' ? webkit : chromium;
const port = process.env.UI_PORT ?? '1493';
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', port, '--strictPort'], {stdio:['ignore','pipe','pipe']});
let browser;
try {
  await new Promise((resolve,reject) => { const timer=setTimeout(() => reject(new Error('Preview timeout')),15000); server.stdout.on('data',c=>{if(String(c).includes(port)){clearTimeout(timer);resolve();}});server.once('exit',reject); });
  browser=await engine.launch({headless:true}); const page=await browser.newPage({reducedMotion:'reduce'}); const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(fixture, {empty:true});
  await page.goto(`http://127.0.0.1:${port}`);
  await page.getByRole('heading',{name:'Your dictation',exact:true}).waitFor();
  await page.evaluate(()=>window.__QA__.stores[2].transcripts.push({transcriptId:'custom-app',timestamp:Date.now(),wordCount:3,durationSeconds:1,processingTimeMs:10,finalText:'Synthetic fixture text',rawText:'Synthetic fixture text',engine:'local',application:{name:'Team Editor',bundleId:'test.team.editor'}}));
  const nav=page.getByRole('navigation',{name:'Main navigation'});
  await nav.getByRole('button',{name:'Settings',exact:true}).click();
  await nav.getByRole('button',{name:'Dictation',exact:true}).click();
  await page.getByLabel('Spoken phrase',{exact:true}).fill('my signature');
  await page.getByLabel('Text to insert',{exact:true}).fill('Thanks,\nHari\n');
  await page.getByRole('button',{name:'Add snippet',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].voiceSnippets?.length===1);
  assert.equal(await page.evaluate(()=>window.__QA__.stores[1].voiceSnippets[0].text),'Thanks,\nHari\n');
  await page.getByRole('button',{name:'Edit my signature',exact:true}).click();
  await page.getByLabel('Text to insert',{exact:true}).fill('Regards,\nHari');
  await page.getByRole('button',{name:'Save snippet',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].voiceSnippets[0].text==='Regards,\nHari');
  await page.getByRole('combobox',{name:'App',exact:true}).click();
  await page.getByRole('option',{name:'Team Editor',exact:true}).waitFor();
  await page.getByRole('option',{name:'Mail',exact:true}).click();
  await page.getByRole('combobox',{name:'App writing style',exact:true}).click();
  await page.getByRole('option',{name:'Formal',exact:true}).click();
  await page.getByRole('button',{name:'Save app style',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].appStyleProfiles?.[0]?.style==='formal');
  assert.equal(await page.getByLabel('App bundle ID',{exact:true}).count(),0,'App configuration uses names instead of implementation identifiers');
  await page.getByText('Other apps use your default style', {exact:false}).waitFor();
  await page.getByRole('button',{name:'Edit Mail style',exact:true}).click();
  await page.getByRole('combobox',{name:'App writing style',exact:true}).click();
  await page.getByRole('option',{name:'Casual',exact:true}).click();
  await page.getByRole('button',{name:'Save app style',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].appStyleProfiles?.[0]?.style==='casual');
  assert.equal(await page.evaluate(()=>window.__QA__.stores[1].appStyleProfiles.length),1,'Editing updates the existing app profile');
  const captured = await page.evaluate(async()=>{
    const {useAppStore}=await import('/src/store/app.store.ts');
    useAppStore.setState({loadedModelFilename:'parakeet-ultra',transcriptionLanguage:'en'});
    return (await import('/src/services/dictation-options.service.ts')).dictationOptions();
  });
  assert.equal(captured.voiceSnippets[0].text,'Regards,\nHari');
  assert.deepEqual(captured.appStyleProfiles,[{bundleId:'com.apple.mail',style:'casual'}]);
  assert.equal(captured.cursorAwareInsertion,false);
  await page.getByRole('button',{name:'Delete my signature',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].voiceSnippets.length===0);
  await page.getByRole('button',{name:'Remove Mail style',exact:true}).click();
  await page.waitForFunction(()=>window.__QA__.stores[1].appStyleProfiles.length===0);
  assert.deepEqual(errors,[]);
  console.log('Personalization CRUD, persisted text, and native options passed.');
} finally { await browser?.close(); server.kill('SIGTERM'); }
